"""gen_prefetch_tables.py: prints Nintendont/kernel/slippi_online/so_prefetch_tables.h, Melee 1.02's character file names by CSS
character (from the DOL's ftData tables: dat, animations, costumes)."""
import os
import struct
ISO = os.environ.get('MELEE_ISO', 'SSBMv102.iso')
f = open(ISO, 'rb'); f.seek(0x420); dol = struct.unpack('>I', f.read(4))[0]
f.seek(dol); h = f.read(0x100)
offs = struct.unpack('>18I', h[0:72]); addrs = struct.unpack('>18I', h[72:144]); sizes = struct.unpack('>18I', h[144:216])
secs = [(a, o, s) for a, o, s in zip(addrs, offs, sizes) if s]
def rd(addr, n):
    for a, o, s in secs:
        if a <= addr < a + s:
            f.seek(dol + o + addr - a); return f.read(n)
    raise KeyError(hex(addr))
def u32(a): return struct.unpack('>I', rd(a, 4))[0]
def cstr(a): b = rd(a, 64); return b[:b.index(b'\0')].decode()
KINDS = 33
dat = [cstr(u32(0x803C1F40 + 8 * k)) for k in range(KINDS)]
aj = [cstr(u32(0x803C23E4 + 4 * k)) for k in range(KINDS)]
ncos = [rd(0x803C0EC0 + 8 * k + 4, 1)[0] for k in range(KINDS)]
fix = lambda n: n + "usd" if n.endswith(".") else n
cos = [[fix(cstr(u32(u32(0x803C2360 + 4 * k) + 12 * c))) for c in range(ncos[k])] for k in range(KINDS)]
# CSS (external) character -> kinds (Ice Climbers and Zelda/Sheik load two)
EXT = [[2], [3], [1], [24], [4], [5], [6], [17], [0], [18], [16], [8], [9], [12], [10, 11], [15], [13], [14],
       [19, 7], [7, 19], [22], [20], [21], [26], [23], [25]]
EF = {0: 'EfMrData.dat', 1: 'EfFxData.dat', 2: 'EfCaData.dat', 3: 'EfDkData.dat', 4: 'EfKbData.dat', 5: 'EfKpData.dat',
      6: 'EfLkData.dat', 7: 'EfZdData.dat', 8: 'EfNsData.dat', 9: 'EfPeData.dat', 10: 'EfIcData.dat', 11: 'EfIcData.dat',
      12: 'EfPkData.dat', 13: 'EfSsData.dat', 14: 'EfYsData.dat', 15: 'EfPrData.dat', 16: 'EfMtData.dat',
      17: 'EfLgData.dat', 18: 'EfMsData.dat', 19: 'EfZdData.dat', 20: 'EfLkData.dat', 21: 'EfMrData.dat',
      22: 'EfFxData.dat', 23: 'EfPkData.dat', 24: 'EfMnData.dat', 25: 'EfGnData.dat', 26: 'EfFeData.dat'}
SSM = ['captain', 'dk', 'fox', 'gw', 'kirby', 'koopa', 'link', 'luigi', 'mario', 'mars', 'mewtwo', 'ness', 'peach',
       'pikachu', 'ice', 'purin', 'samus', 'yoshi', 'zs', 'zs', 'falco', 'clink', 'drmario', 'emblem', 'pichu', 'ganon']
print('/* Generated by tools/gen_prefetch_tables.py from Melee 1.02\'s DOL (ftData tables): the files a')
print(' * character loads, by CSS character. Costume files in costume order. */')
print('typedef struct { const char *dat, *aj, *ef; const char *costume[6]; } PfKind;')
print('static const PfKind pf_kinds[] = {')
for k in range(27):
    cs = ', '.join(f'"{c}"' for c in cos[k][:6])
    print(f'\t{{ "{dat[k]}", "{aj[k]}", "{EF[k]}", {{ {cs} }} }},\t/* {k} */')
print('};')
print('/* CSS character -> kinds (a second, or -1), and its sound bank */')
print('static const struct { s8 kind[2]; const char *ssm; } pf_chars[] = {')
for e, ks in enumerate(EXT):
    print(f'\t{{ {{ {ks[0]}, {ks[1] if len(ks) > 1 else -1} }}, "audio/us/{SSM[e]}.ssm" }},\t/* {e} */')
print('};')
